"""Create a public GitHub Release containing Bodhan-generated voice fixtures."""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = "SriKrishnaMishra/Tool-Server-and-Task-Agent"
TAG = "voice-samples-v1"
SAMPLES = (
    ROOT / "demo" / "inputs" / "voice-note.wav",
    ROOT / "demo" / "inputs" / "clips" / "clip-1-te.wav",
    ROOT / "demo" / "inputs" / "clips" / "clip-2-hi.wav",
    ROOT / "demo" / "inputs" / "clips" / "clip-3-en.wav",
    ROOT / "demo" / "inputs" / "clips" / "clip-4-te.wav",
    ROOT / "demo" / "inputs" / "clips" / "clip-5-ta.wav",
)


def find_gh() -> str:
    executable = shutil.which("gh")
    if executable:
        return executable
    windows_path = Path(
        r"C:\Program Files\GitHub CLI\gh.exe"
    )
    if windows_path.is_file():
        return str(windows_path)
    raise RuntimeError("GitHub CLI is not installed or not on PATH.")


def gh(*arguments: str) -> str:
    return subprocess.run(
        [find_gh(), *arguments],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()


def main() -> int:
    missing = [str(path) for path in SAMPLES if not path.is_file()]
    if missing:
        print("Missing generated voice samples:", file=sys.stderr)
        for path in missing:
            print(f"  {path}", file=sys.stderr)
        print(
            "Run: python demo/create_fixtures.py",
            file=sys.stderr,
        )
        return 1

    try:
        gh("auth", "status")
    except subprocess.CalledProcessError as exc:
        print(
            "GitHub CLI is not authenticated.",
            file=sys.stderr,
        )
        print(
            "Run: gh auth login --hostname github.com --git-protocol https --web",
            file=sys.stderr,
        )
        if exc.stderr:
            print(exc.stderr.strip(), file=sys.stderr)
        return 1

    try:
        gh(
            "release",
            "view",
            TAG,
            "--repo",
            REPOSITORY,
        )
    except subprocess.CalledProcessError:
        gh(
            "release",
            "create",
            TAG,
            *(str(path) for path in SAMPLES),
            "--repo",
            REPOSITORY,
            "--title",
            "AI-Generated Bodhan Voice Samples",
            "--notes",
            "All audio was generated by Bodhan Indic-Speak and is not human-recorded audio.",
        )
    else:
        gh(
            "release",
            "upload",
            TAG,
            *(str(path) for path in SAMPLES),
            "--repo",
            REPOSITORY,
            "--clobber",
        )

    release_url = (
        f"https://github.com/{REPOSITORY}/releases/tag/{TAG}"
    )
    print(release_url)
    for path in SAMPLES:
        print(
            f"https://github.com/{REPOSITORY}/releases/download/"
            f"{TAG}/{path.name}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
